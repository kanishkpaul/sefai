import contextlib
import importlib.util
import io
import subprocess
import tempfile
import unittest
from pathlib import Path

CHECKER = Path(__file__).resolve().parents[1] / "scripts/check_attribution.py"
spec = importlib.util.spec_from_file_location("attribution", CHECKER)
attribution = importlib.util.module_from_spec(spec)
spec.loader.exec_module(attribution)


class AttributionTests(unittest.TestCase):
    def rejects(self, text):
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertFalse(attribution.check(text, "fixture"))

    def test_rejects_any_coauthor(self):
        self.rejects("Co-Authored-By: Someone <someone@example.com>")

    def test_rejects_mixed_case_trailer(self):
        self.rejects("cO-aUtHoReD-bY: Assistant <bot@example.com>")

    def test_rejects_unknown_ai_signature(self):
        self.rejects("Generated by an AI coding assistant")

    def test_rejects_markdown_signature(self):
        self.rejects("<!-- Written with Claude Code -->")

    def test_allows_technical_discussion(self):
        self.assertTrue(attribution.check("Fix the MCP client for Claude Desktop", "fixture"))

    def test_message_command_fails_on_attribution(self):
        with tempfile.TemporaryDirectory() as directory:
            message = Path(directory) / "message"
            message.write_text("Fix streaming\n\nCo-Authored-By: Bot <bot@example.com>\n")
            result = subprocess.run(["python3", str(CHECKER), "message", str(message)], capture_output=True)
        self.assertEqual(result.returncode, 1)

    def test_message_command_fails_on_missing_file(self):
        with tempfile.TemporaryDirectory() as directory:
            result = subprocess.run(["python3", str(CHECKER), "message", str(Path(directory) / "missing")], capture_output=True)
        self.assertNotEqual(result.returncode, 0)


class RevisionTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        self.run_git("init", "-q")
        self.run_git("config", "user.name", "Fixture")
        self.run_git("config", "user.email", "fixture@example.com")
        self.base = self.commit("Initial fixture", "fixture.txt", "original\n")

    def run_git(self, *arguments):
        return subprocess.check_output(["git", *arguments], cwd=self.root, text=True)

    def commit(self, message, path, content):
        file = self.root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(content)
        self.run_git("add", "--", path)
        self.run_git("commit", "-q", "-m", message)
        return self.run_git("rev-parse", "HEAD").strip()

    def checker(self, command, head):
        return subprocess.run(["python3", str(CHECKER), command, self.base, head], cwd=self.root, capture_output=True)

    def test_range_rejects_earlier_attributed_commit(self):
        self.commit("Fix loading\n\nCo-Authored-By: Bot <bot@example.com>", "fixture.txt", "changed\n")
        head = self.commit("Fix streaming", "fixture.txt", "final\n")
        self.assertEqual(self.checker("range", head).returncode, 1)

    def test_range_excludes_existing_history(self):
        head = self.commit("Fix loading", "fixture.txt", "changed\n")
        self.assertEqual(self.checker("range", head).returncode, 0)

    def test_diff_rejects_added_signature(self):
        head = self.commit("Fix loading", "src.rs", "// Generated by Claude Code\n")
        self.assertEqual(self.checker("diff", head).returncode, 1)

    def test_diff_allows_removing_signature(self):
        self.base = self.commit("Fixture signature", "src.rs", "// Generated by Claude Code\n")
        head = self.commit("Remove signature", "src.rs", "fn main() {}\n")
        self.assertEqual(self.checker("diff", head).returncode, 0)

    def test_diff_allows_policy_explanation(self):
        head = self.commit("Document policy", "AGENTS.md", "Do not add `Co-Authored-By` trailers.\n")
        self.assertEqual(self.checker("diff", head).returncode, 0)

    def test_invalid_range_fails_closed(self):
        result = subprocess.run(["python3", str(CHECKER), "range", "missing", self.base], cwd=self.root, capture_output=True)
        self.assertNotEqual(result.returncode, 0)


if __name__ == "__main__":
    unittest.main()
